-------------- COMPROBAMOS GRANULARIDAD --------------

SELECT
    IDEESS,
    PRODUCT_KEY,
    INGESTION_TS,
    COUNT(*) AS NUM_REGISTROS
FROM GOLD.FACT_FUEL_PRICE
GROUP BY
    IDEESS,
    PRODUCT_KEY,
    INGESTION_TS
HAVING COUNT(*) > 1;



